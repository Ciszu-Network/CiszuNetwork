/**
 * Interpolación mínima para textos con marcadores `{nombre}`.
 * Se usa en lugar de traer una librería de i18n: las cadenas ya viven aquí y
 * lo único que falta es sustituir valores.
 */
export function t(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in vars ? String(vars[key]) : match
  );
}

