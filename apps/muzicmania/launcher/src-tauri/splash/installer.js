var currentLang = "1034", isFinished = false;

function applyLang(lang) {
  if (!I18N[lang]) lang = "1033";
  currentLang = lang;
  var t = I18N[lang];
  for (var key in t) { var el = $(key); if (el) el.textContent = t[key]; }
  $("sel-lang").value = lang;
  ipc("installer_set_lang", { lang: parseInt(lang) });
}

function goView(id) {
  var views = document.querySelectorAll(".view");
  for (var i = 0; i < views.length; i++) views[i].classList.remove("active");
  $(id).classList.add("active");
}

function goBack() {
  var active = document.querySelector(".view.active");
  if (!active) return;
  if (active.id === "v-welcome") goView("v-lang");
  else if (active.id === "v-license") goView("v-welcome");
  else if (active.id === "v-dir") goView("v-license");
}

function onLicenseCheck() {
  $("btn-license-next").disabled = !$("chk-license").checked;
}

function onBrowse() {
  ipc("installer_pick_dir").then(function(dir) { if (dir) $("install-dir").value = dir; });
}

function log(msg, type) {
  var c = $("inst-console");
  if (!c) return;
  var d = document.createElement("div");
  d.className = type || "info";
  d.textContent = msg;
  c.appendChild(d);
  c.scrollTop = c.scrollHeight;
}

function setProgress(pct) {
  $("inst-progress").style.width = pct + "%";
  $("inst-pct").textContent = pct + "%";
}

function startInstall() {
  goView("v-installing");
  log("Iniciando proceso de instalaci\u00f3n...", "info");
  setProgress(0);
  var dir = $("install-dir").value;
  var maxPoll = 240;
  ipc("installer_set_dir", { dir: dir }).then(function() {
    ipc("installer_start_install");
    var poll = function() {
      if (--maxPoll <= 0) {
        goView("v-finish");
        return;
      }
      ipc("installer_read_status").then(function(status) {
        if (status === "READY" || status === null) {
          ipc("installer_read_progress").then(function(pct) { if (pct !== null) setProgress(Math.min(parseInt(pct)||0, 100)); });
          ipc("installer_read_log").then(function(lines) { if (lines) { var parts = lines.split("\n"); for (var i = 0; i < parts.length; i++) { var p = parts[i].trim(); if (p) log(p, "ok"); } } });
          setTimeout(poll, 500);
        } else {
          finishInstall();
        }
      });
    };
    poll();
  });
}

function finishInstall() {
  setProgress(100);
  $("inst-status").textContent = "Completado";
  log("Instalaci\u00f3n finalizada correctamente.", "ok");
  isFinished = true;
  setTimeout(function() { goView("v-finish"); }, 800);
}

function onFinish() {
  ipc("installer_finish", {
    run: $("chk-run").checked,
    desktop: $("chk-desktop").checked,
    taskbar: $("chk-taskbar").checked,
    changelog: $("chk-changelog").checked
  }).then(function() { window.close(); });
}

window.showCloseModal = function() {
  if (isFinished) { window.close(); return; }
  $("close-modal").classList.add("active");
};

function init() {
  applyLang("1034");
  ipc("installer_info").then(function(info) {
    if (info && info.dir) $("install-dir").value = info.dir;
    if (info && info.version && info.os && info.arch) {
      $("sys-info").textContent = "MuzicMania v" + info.version + " (" + info.os + " " + info.arch + ")";
    }
  });

  $("sel-lang").addEventListener("change", function() { applyLang(this.value); });
  $("chk-license").addEventListener("change", onLicenseCheck);
  $("btn-lang-next").addEventListener("click", function() { goView("v-welcome"); });
  $("btn-welcome-back").addEventListener("click", function() { goView("v-lang"); });
  $("btn-welcome-next").addEventListener("click", function() { goView("v-license"); });
  $("btn-license-back").addEventListener("click", function() { goView("v-welcome"); });
  $("btn-license-next").addEventListener("click", function() { goView("v-dir"); });
  $("btn-dir-back").addEventListener("click", function() { goView("v-license"); });
  $("btn-dir-install").addEventListener("click", startInstall);
  $("btn-browse").addEventListener("click", onBrowse);
  $("btn-finish").addEventListener("click", onFinish);
  $("btn-modal-no").addEventListener("click", function() { $("close-modal").classList.remove("active"); });
  $("btn-modal-yes").addEventListener("click", function() { ipc("installer_force_close"); window.close(); });

  document.addEventListener("contextmenu", function(e) { e.preventDefault(); });
  document.addEventListener("keydown", function(e) {
    if (e.key === "F3" || e.key === "F5" || e.key === "F12" || (e.ctrlKey && ["p","r","f"].indexOf(e.key.toLowerCase()) !== -1)) e.preventDefault();
  });
}

if (document.readyState === "complete" || document.readyState === "interactive") {
  init();
} else {
  document.addEventListener("DOMContentLoaded", init);
}
